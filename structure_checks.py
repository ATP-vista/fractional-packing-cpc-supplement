"""Exact finite checks for the equality cases in Sections 4, 8 and 9.

1. Theorem 4.2 with input budgets, on small capped networks over F_2 (demand-1 length 2 and 3) with demands
   in both I_< and I':
   every deterministic code with H(T|W)=D has posteriors = (translate of a cell of the bottleneck input map)
   x (coset of one fixed subgroup G), and G equals the period group of Lemma 4.7.
2. Example 4.5 (input bottleneck): H_alpha = D for all alpha, but the support is neither affine nor periodic.
3. Control, Example 4.4 over F_3 (saturated node): a cut-attaining code whose posterior supports are not cosets,
   so the coset test is not vacuous and the hypothesis V_1 = empty matters.
4. Section 9 example: S in F_5^3 attains |S|^2 = max slice * |pi_12 S| * |pi_13 S| with no periodic slice;
   random sets never exceed the bound.
5. Section 8.2 parabola code over odd p: P_c = 1/p and H = 2 - 1/p (base p).
6. Proposition 8.3 padding: packing numbers of the padded two-block network (fractional 3, integral 2).
7. Theorem 4.3: period groups of Shannon cut-attaining codes equal the subspaces with quotient rank of total M within every node budget,
   each realized by its local quotient code (full-input networks over F_2 and F_3), with failing controls.

Run with Python 3: python -B structure_checks.py
"""
import itertools
import math
import random
from fractions import Fraction


def set_partitions_rgs(n, kmax):
    """All restricted growth strings of length n with at most kmax blocks (set partitions)."""
    out = []

    def rec(prefix, m):
        if len(prefix) == n:
            out.append(tuple(prefix))
            return
        for b in range(min(m + 1, kmax)):
            rec(prefix + [b], max(m, b + 1))

    rec([], 0)
    return out


def entropy_bits(counts):
    tot = sum(counts)
    return -sum(c / tot * math.log2(c / tot) for c in counts if c)


def span_group(vectors, n):
    """Subgroup of F_2^n (ints as bit vectors) generated by vectors."""
    g = {0}
    for v in vectors:
        if v not in g:
            g = g | {x ^ v for x in g}
    return frozenset(g)


# ---------------------------------------------------------------- 1. capped network
def check_capped_network(L1):
    # Demand 1 has length L1 and input budget 1 at its only holder u; demands 2, 3 are scalar, held by u and v.
    # Exact LP certificate: primal r = (1, 1/2, 1/2), dual y_u = y_v = u_1 = 1/2.
    F = Fraction
    c_u, c_v, h1, L = 2, 1, 1, (L1, 1, 1)
    r = (F(1), F(1, 2), F(1, 2))
    assert r[0] <= h1 and r[0] + r[1] + r[2] <= c_u and r[1] + r[2] <= c_v
    y_u, y_v, u1 = F(1, 2), F(1, 2), F(1, 2)
    assert y_u + u1 >= 1 and y_u + y_v >= 1
    M = sum(r)
    assert c_u * y_u + c_v * y_v + h1 * u1 == M == 2
    D = sum(L) - M
    assert D == L1
    # Dual optimal set is {y_u=t, y_v=1-t, u_1=1-t, u_2=u_3=0 : t in [0,1]}: relative interior has
    # Y_1 = t < 1 (demand 1 in I_<) and Y_2 = Y_3 = 1; no node saturated. I' = {2,3}, D' = 1.
    n1 = 2 ** L1
    phis = set_partitions_rgs(n1, 2)         # input map of demand 1 (L1 bits -> 1 bit)
    fus = set_partitions_rgs(8, 4)           # node u: (phi, x_u2, x_u3) -> 4 labels
    fvs = set_partitions_rgs(4, 2)           # node v: (x_v2, x_v3) -> 2 labels
    inputs = list(itertools.product(range(n1), range(2), range(2), range(2), range(2)))
    N = len(inputs)
    n_codes = n_opt = n_nonaffine = n_control_vary = 0
    for phi in phis:
        cells = {}
        for x in range(n1):
            cells.setdefault(phi[x], set()).add(x)
        cells = [frozenset(c) for c in cells.values()]
        for fv in fvs:
            for fu in fus:
                n_codes += 1
                post = {}
                for (x1, xu2, xu3, xv2, xv3) in inputs:
                    zu = fu[phi[x1] * 4 + xu2 * 2 + xu3]
                    zv = fv[xv2 * 2 + xv3]
                    t = (x1, (xu2 ^ xv2) * 2 + (xu3 ^ xv3))
                    d = post.setdefault((zu, zv), {})
                    d[t] = d.get(t, 0) + 1
                H = sum(sum(d.values()) / N * entropy_bits(list(d.values())) for d in post.values())
                full = 2 ** D
                uniform = all(len(d) == full and len(set(d.values())) == 1 for d in post.values())
                assert H >= D - 1e-12, "cut bound violated"
                if abs(H - D) > 1e-12:
                    assert not uniform
                    # control: a code above the cut whose supports are products of a cell translate and a
                    # coset, but whose subgroup depends on the transcript (shows the one-G test can fail)
                    gs = set()
                    ok = True
                    for d in post.values():
                        K23 = {t[1] for t in d}
                        G = span_group([a ^ b for a in K23 for b in K23], 2)
                        ok = ok and len(G) == len(K23) and set(d) == {(a, b) for a in {t[0] for t in d} for b in K23}
                        gs.add(G)
                    if ok and len(gs) > 1:
                        n_control_vary += 1
                    continue
                n_opt += 1
                assert uniform
                # Theorem 4.2 structure
                groups = set()
                for d in post.values():
                    K = set(d)
                    K1 = {t[0] for t in K}
                    K23 = {t[1] for t in K}
                    assert K == {(a, b) for a in K1 for b in K23}, "not a product"
                    assert any(K1 == {c ^ y for y in cell} for cell in cells for c in range(n1)), "not a cell"
                    if len(span_group([a ^ b for a in K1 for b in K1], L1)) > len(K1):
                        n_nonaffine += 1
                    G = span_group([a ^ b for a in K23 for b in K23], 2)
                    assert len(G) == 2 and K23 == {next(iter(K23)) ^ g for g in G}, "not a coset"
                    groups.add(G)
                assert len(groups) == 1, "subgroup depends on the transcript"
                G = groups.pop()
                # Lemma 4.7: G is generated by the I'-projected fibre differences of both nodes
                diffs = []
                fib_u, fib_v = {}, {}
                for x1 in range(n1):
                    for xu2 in range(2):
                        for xu3 in range(2):
                            fib_u.setdefault(fu[phi[x1] * 4 + xu2 * 2 + xu3], []).append(xu2 * 2 + xu3)
                for xv2 in range(2):
                    for xv3 in range(2):
                        fib_v.setdefault(fv[xv2 * 2 + xv3], []).append(xv2 * 2 + xv3)
                for fib in list(fib_u.values()) + list(fib_v.values()):
                    diffs += [a ^ b for a in fib for b in fib]
                assert span_group(diffs, 2) == G, "period group differs from Lemma 4.7"
                # quotient rank: rho(I') = M' = 1, rho({i}) <= 1 = h_i, rho(I') <= c'_u = c'_v = 1
                rho = lambda J: (len(J) - math.log2(len([g for g in G if all(((g >> (1 - j)) & 1) == 0 or j in J for j in (0, 1))])))
                assert rho((0, 1)) == 1 and rho((0,)) <= 1 and rho((1,)) <= 1
    print(f"[1] capped network over F_2, L1={L1}: {n_codes} label-normalized map tables, {n_opt} with H(T|W)=D={D};"
          f" every posterior = (cell translate) x (coset of one G), G = Lemma 4.7 group;"
          f" non-affine cell factors seen {n_nonaffine} times; control codes with transcript-dependent G: {n_control_vary}")
    assert (n_codes, n_opt) == {2: (178880, 9), 3: (2862080, 105)}[L1]
    assert n_control_vary > 0
    if L1 == 3:
        assert n_nonaffine > 0
    return n_opt


# ---------------------------------------------------------------- 2. Example 4.5
def check_input_cell_example():
    A = {0b000, 0b001, 0b010, 0b100}
    Ac = set(range(8)) - A
    for S in (A, Ac):
        assert len(S) == 4
        assert all({s ^ v for s in S} != S for v in range(1, 8)), "unexpected period"
    affine = any(A == {a ^ g for g in span_group(gens, 3)} and len(span_group(gens, 3)) == 4
                 for a in range(8) for gens in itertools.combinations(range(1, 8), 2))
    assert not affine
    # no nonzero linear functional is constant on A (A spans F_2^3 and contains 0)
    for lam in range(1, 8):
        assert len({bin(lam & s).count('1') % 2 for s in A}) == 2
    # LP: P = [0,1], M = 1, D = 2; dual min 2y+u, y+u>=1, 0<=y<=1 has unique optimum (0,1)
    vals = {Fraction(k, 100): 2 * Fraction(k, 100) + (1 - Fraction(k, 100)) for k in range(101)}
    assert min(vals.values()) == 1 and [y for y, v in vals.items() if v == 1] == [0]
    print("[2] Example 4.5: posteriors uniform of size 4 = 2^D; A is not affine, has no period, "
          "and determines no nonzero linear functional")


# ---------------------------------------------------------------- 3. saturated control
def check_saturated_control():
    q = 3
    pts = [(a, b) for a in range(q) for b in range(q)]
    # partition of F_3^2 into 3 sets of size 3, one of them not a line
    cells = [{(0, 0), (0, 1), (1, 0)}, {(0, 2), (1, 1), (2, 0)}, {(1, 2), (2, 1), (2, 2)}]
    assert sorted(p for c in cells for p in c) == sorted(pts)

    def is_coset(S):
        s0 = next(iter(S))
        G = {((a - s0[0]) % q, (b - s0[1]) % q) for (a, b) in S}
        closed = all(((g[0] + h[0]) % q, (g[1] + h[1]) % q) in G for g in G for h in G)
        return closed

    n_noncoset = sum(not is_coset(c) for c in cells)
    assert n_noncoset >= 1, "control failed to produce a non-coset support"
    print(f"[3] control, Example 4.4 over F_3: uniform posteriors of size 3 = q^D with {n_noncoset} "
          "non-coset supports; the coset assertion of Theorem 4.2 fails without V_1 = empty, as stated")


# ---------------------------------------------------------------- 4. Section 9 slices
def check_box_without_period():
    p = 5
    S = {(0, b, c) for b in (0, 1) for c in (0, 1)} | {(1, b, c) for b in (0, 2) for c in (0, 2)}

    def stats(S):
        slices = {}
        for (a, b, c) in S:
            slices.setdefault(a, set()).add((b, c))
        m = max(len(v) for v in slices.values())
        p12 = {(a, b) for (a, b, c) in S}
        p13 = {(a, c) for (a, b, c) in S}
        return slices, m, len(p12), len(p13)

    slices, m, n12, n13 = stats(S)
    assert len(S) ** 2 == m * n12 * n13 == 64
    for sl in slices.values():
        for v in itertools.product(range(p), repeat=2):
            if v != (0, 0):
                assert {((b + v[0]) % p, (c + v[1]) % p) for (b, c) in sl} != sl
    rng = random.Random(20261118)
    universe = list(itertools.product(range(p), repeat=3))
    for _ in range(20000):
        T = set(rng.sample(universe, rng.randint(1, 40)))
        _, m, n12, n13 = stats(T)
        assert len(T) ** 2 <= m * n12 * n13
    print("[4] Section 9: S attains 64 = 4*4*4 with box slices of equal sides and no nonzero period; "
          "20000 random sets respect the bound")


# ---------------------------------------------------------------- 5. parabola code
def check_parabola():
    for p in (3, 5, 7, 11):
        post = {}
        for a, b, c, d in itertools.product(range(p), repeat=4):
            z = ((b - a * a) % p, (d + c * c) % p)
            t = ((a + c) % p, (b + d) % p)
            post.setdefault(z, {}).setdefault(t, 0)
            post[z][t] += 1
        N = p ** 4
        Pc = Fraction(sum(max(dd.values()) for dd in post.values()), N)
        H = sum(sum(dd.values()) / N * entropy_bits(list(dd.values())) for dd in post.values()) / math.log2(p)
        spectra = {tuple(sorted(dd.values(), reverse=True)) for dd in post.values()}
        assert Pc == Fraction(1, p)
        assert spectra == {tuple([p] + [1] * (p * (p - 1)))}
        assert abs(H - (2 - 1 / p)) < 1e-12
    print("[5] parabola code: P_c = 1/p and H = 2 - 1/p for p = 3, 5, 7, 11")


# ---------------------------------------------------------------- 6. padded two-block network
def check_padding():
    A, B = (0, 1, 2), (3, 4, 5)
    for s in (1, 2, 3):
        pad = tuple(range(6, 7 + s))
        nodes = [A, B] + [(a, b) for a in A for b in B] + [pad]
        # fractional: primal r = 1/3 on A u B, r_pad = (1,0,...,0); dual y = 1 on w1, w2 and the pad node
        r = [Fraction(1, 3)] * 6 + [Fraction(1)] + [Fraction(0)] * s
        assert all(sum(r[i] for i in n) <= 1 for n in nodes)
        y = {0: 1, 1: 1, len(nodes) - 1: 1}
        assert all(sum(y.get(k, 0) for k, n in enumerate(nodes) if i in n) >= 1 for i in range(7 + s))
        assert sum(r) == sum(y.values()) == 3
        best = max(sum(x) for x in itertools.product((0, 1), repeat=7 + s)
                   if all(sum(x[i] for i in n) <= 1 for n in nodes))
        assert best == 2
    print("[6] padded two-block network, s = 1, 2, 3: fractional packing 3 (certified), integral packing 2")


# ---------------------------------------------------------------- 7. Theorem 4.3 (classification)
def all_subgroups_f2(n):
    gens = range(1, 2 ** n)
    out = {frozenset({0})}
    for k in range(1, n + 1):
        for g in itertools.combinations(gens, k):
            out.add(span_group(g, n))
    return out


def check_classification_f2():
    """Full inputs over F_2: demand 1 (bit 2) held by u only; demands 2, 3 (bits 1, 0) held by u and v;
    c_u = 2, c_v = 1. M = 2, D = 1; dual y_u = y_v = u_1 = 1/2 (no saturated node), demand 1 in I_<."""
    S_u, S_v = (2, 1, 0), (1, 0)

    def rho(G, J):
        inside = [g for g in G if all(((g >> b) & 1) == 0 or b in J for b in (0, 1, 2))]
        return len(J) - math.log2(len(inside))

    admissible = {G for G in all_subgroups_f2(3)
                  if rho(G, S_u) <= 2 and rho(G, S_v) <= 1 and rho(G, (0, 1, 2)) == 2}
    fus = set_partitions_rgs(8, 4)
    fvs = set_partitions_rgs(4, 2)
    found = set()
    n_opt = 0
    for fu in fus:
        for fv in fvs:
            post = {}
            for xu in range(8):
                for xv in range(4):
                    t = xu ^ xv            # demand 1 = bit 2 of xu; demands 2, 3 summed bitwise
                    post.setdefault((fu[xu], fv[xv]), {}).setdefault(t, 0)
                    post[(fu[xu], fv[xv])][t] += 1
            H = sum(sum(d.values()) / 32 * entropy_bits(list(d.values())) for d in post.values())
            assert H >= 1 - 1e-12
            if abs(H - 1) > 1e-12:
                continue
            n_opt += 1
            gs = {span_group([a ^ b for a in d for b in d], 3) for d in post.values()}
            assert len(gs) == 1
            G = gs.pop()
            assert all(len(d) == len(G) for d in post.values())
            found.add(G)
    assert found == admissible, (found, admissible)
    # (ii) => (i): local quotient codes; control: inadmissible subgroups fail budget or equality
    n_control = 0
    for G in all_subgroups_f2(3):
        Gu = frozenset(G)                                  # all of G is supported in S_u = I
        Gv = frozenset(g for g in G if (g >> 2) & 1 == 0)  # part supported in S_v
        nu, nv = 8 // len(Gu), 4 // len(Gv)
        post = {}
        for xu in range(8):
            for xv in range(4):
                z = (min(xu ^ g for g in Gu), min(xv ^ g for g in Gv))
                post.setdefault(z, set()).add(xu ^ xv)
        H = math.log2(len(next(iter(post.values()))))
        ok = nu <= 4 and nv <= 2 and abs(H - 1) < 1e-12 and all(
            d == {next(iter(d)) ^ g for g in G} for d in post.values())
        assert ok == (G in admissible)
        n_control += not ok
    print(f"[7a] Theorem 4.3 over F_2: {n_opt} Shannon cut-attaining codes (up to relabelling); their period groups are "
          f"exactly the {len(admissible)} subgroups satisfying (ii); each local quotient code realizes its group; "
          f"{n_control} other subgroups fail as controls")


def check_classification_f3():
    """Full inputs over F_3: nodes u, v both hold scalar demands 1, 2; c_u = c_v = 1; M = D = 1, both fractional.
    By (U2c) fibres of Shannon cut-attaining codes are balanced, so only balanced partitions are enumerated."""
    q = 3
    pts = [(a, b) for a in range(q) for b in range(q)]
    all_parts = set_partitions_rgs(9, 3)
    assert len(all_parts) == 3281
    parts = [P for P in all_parts if sorted(P.count(k) for k in range(3)) == [3, 3, 3]]
    assert len(parts) == 280
    add = lambda x, y: ((x[0] + y[0]) % q, (x[1] + y[1]) % q)
    sub = lambda x, y: ((x[0] - y[0]) % q, (x[1] - y[1]) % q)
    lines = set()
    for d in pts[1:]:
        lines.add(frozenset({(k * d[0] % q, k * d[1] % q) for k in range(q)}))
    assert len(lines) == 4
    found, n_opt, n_nonlinear_node = set(), 0, 0
    for Pu in parts:
        for Pv in parts:
            post = {}
            for i, xu in enumerate(pts):
                for j, xv in enumerate(pts):
                    t = add(xu, xv)
                    d = post.setdefault((Pu[i], Pv[j]), {})
                    d[t] = d.get(t, 0) + 1
            if not all(len(d) == 3 and set(d.values()) == {3} for d in post.values()):
                H = sum(9 * entropy_bits(list(d.values())) for d in post.values()) / 81 / math.log2(3)
                assert H > 1 + 1e-12
                continue
            n_opt += 1
            gs = {frozenset(sub(a, b) for a in d for b in d) for d in post.values()}
            assert len(gs) == 1
            G = gs.pop()
            assert G in lines
            found.add(G)
    assert found == lines
    print(f"[7b] Theorem 4.3 over F_3 (two nodes, two common demands): {len(parts)**2} balanced pairs out of {len(all_parts)**2} possible pairs; {n_opt} attain the Shannon cut; "
          f"period groups = all 4 lines = the subgroups satisfying (ii)")


def check_interval_triangle():
    """Section 2.6: native label counts and conditional sum supports over F_101."""
    p = 101
    bins = [[] for _ in range(10)]
    for x in range(p):
        bins[10 * x // p].append(x)
    assert sorted(map(len, bins)) == [10] * 9 + [11]
    # Both inputs range independently, so every ordered bin pair uses one output label.
    labels = len(bins) ** 2
    sizes = [len({(x + y) % p for x in left for y in right})
             for left in bins for right in bins]
    assert labels == len(sizes) == 100 <= p
    assert max(sizes) == 21 and max(sizes) ** 3 < p ** 2
    # Keeping eleven nonempty bins at each input would exceed the output alphabet.
    assert 11 ** 2 > p
    print(f"F_101 triangle: {labels} output labels, largest scalar sum support {max(sizes)}; "
          f"{max(sizes)**3} < {p**2}; eleven-bin control exceeds the output budget.")


